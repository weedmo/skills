#!/usr/bin/env node
// hc worker helper for the delegated loops (see ../SKILL.md).
//
//   hc-worker.mjs templates --roles <dir> [--roles <dir> ...]
//   hc-worker.mjs start --run <slug> --name <terminal> --role <template>
//                       --cwd <dir> --task-file <file> --state <file> [--on <machine>]
//
// `templates` turns role files into hc templates: a Claude Code agent
// (<role>.md with model/effort frontmatter) becomes <role>-claude, a Codex
// role (<role>.toml) becomes <role>-codex. `start` launches one worker from a
// template and, inside a Herdr window, shows every worker of a run in one tab.
// Both print one JSON object; exit 1 means nothing was launched or written.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const MARKER = "<!-- generated by weed-harness hc-workers; edits are overwritten -->";
const FLAGS = {
  claude: process.env.HC_WORKER_CLAUDE_FLAGS ?? "--permission-mode acceptEdits",
  codex: process.env.HC_WORKER_CODEX_FLAGS ?? "-s workspace-write -a on-request",
};

const fail = (msg) => {
  console.log(JSON.stringify({ error: msg }));
  process.exit(1);
};

function parseArgs(argv) {
  const out = { roles: [] };
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i]?.replace(/^--/, "");
    const value = argv[i + 1];
    if (!argv[i]?.startsWith("--") || value === undefined) fail(`bad argument: ${argv[i]}`);
    if (key === "roles") out.roles.push(value);
    else out[key] = value;
  }
  return out;
}

export function templatesDir() {
  if (process.env.HC_TEMPLATES_DIR) return process.env.HC_TEMPLATES_DIR;
  const config = process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config");
  return path.join(config, "herdr-core", "templates");
}

// A Claude Code agent file: `---` frontmatter with name/description/model/effort, then the prompt.
export function fromClaudeAgent(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return null;
  const meta = Object.fromEntries(
    m[1].split("\n").map((l) => l.match(/^([\w-]+):\s*(.*)$/)).filter(Boolean).map((x) => [x[1], x[2].trim()]),
  );
  if (!meta.name || !meta.model) return null;
  const command = ["claude", "--model", meta.model, meta.effort ? `--effort ${meta.effort}` : "", FLAGS.claude];
  return { name: `${meta.name}-claude`, description: meta.description || meta.name, command: command.filter(Boolean).join(" "), body: m[2].trim() };
}

// A Codex role file: flat `key = "value"` lines plus a triple-quoted developer_instructions.
export function fromCodexRole(text) {
  const body = (text.match(/^developer_instructions\s*=\s*"""\n?([\s\S]*?)"""/m) || [])[1] || "";
  const meta = {};
  for (const l of text.replace(/^developer_instructions[\s\S]*?"""[\s\S]*?"""/m, "").split("\n")) {
    const x = l.match(/^([\w-]+)\s*=\s*"(.*)"\s*$/);
    if (x) meta[x[1]] = x[2];
  }
  if (!meta.name || !meta.model) return null;
  const extra = Object.entries(meta)
    .filter(([k]) => !["name", "description", "model"].includes(k))
    .map(([k, v]) => `-c ${k}=${v}`);
  return { name: `${meta.name}-codex`, description: meta.description || meta.name, command: ["codex", "-m", meta.model, ...extra, FLAGS.codex].filter(Boolean).join(" "), body: body.trim() };
}

function render(t) {
  return `---\nname: ${t.name}\ndescription: ${t.description.replace(/^"|"$/g, "").replace(/\s+/g, " ")}\ncommand: ${t.command}\n---\n\n${t.body}\n\nYou are an hc worker. Start no other agents. Report the way the task says, with \`hc send\`; never report only in prose.\n\n${MARKER}\n`;
}

function templates(args) {
  if (!args.roles.length) fail("templates needs --roles <dir>");
  const dir = templatesDir();
  fs.mkdirSync(dir, { recursive: true });
  const written = [], kept = [], skipped = [];
  for (const roles of args.roles) {
    if (!fs.existsSync(roles)) fail(`roles directory not found: ${roles}`);
    for (const file of fs.readdirSync(roles).sort()) {
      const text = fs.readFileSync(path.join(roles, file), "utf8");
      const t = file.endsWith(".md") ? fromClaudeAgent(text) : file.endsWith(".toml") ? fromCodexRole(text) : null;
      if (!t) continue;
      const target = path.join(dir, `${t.name}.md`);
      const next = render(t);
      const prev = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
      // A template without the marker is the user's own: never overwrite it.
      if (prev !== null && !prev.includes(MARKER)) skipped.push(t.name);
      else if (prev === next) kept.push(t.name);
      else {
        fs.writeFileSync(target, next);
        written.push(t.name);
      }
    }
  }
  console.log(JSON.stringify({ dir, written, kept, skipped }));
}

const run = (bin, argv) => execFileSync(bin, argv, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

// The tab that holds a terminal, from `herdr-app ls`.
export function findTab(tree, terminal) {
  if (Array.isArray(tree)) {
    for (const v of tree) {
      const hit = findTab(v, terminal);
      if (hit) return hit;
    }
  } else if (tree && typeof tree === "object") {
    if (Array.isArray(tree.terminals) && tree.id && tree.terminals.some((t) => t.terminal === terminal)) return tree.id;
    return findTab(Object.values(tree), terminal);
  }
  return null;
}

function start(args) {
  for (const k of ["run", "name", "role", "cwd", "task-file", "state"]) if (!args[k]) fail(`start needs --${k}`);
  const me = process.env.HC_TERMINAL_ID;
  if (!me) fail("not inside an hc terminal (HC_TERMINAL_ID unset): workers would have no parent to report to");
  const task = fs.readFileSync(args["task-file"], "utf8").trim();
  let state = {};
  if (fs.existsSync(args.state)) state = JSON.parse(fs.readFileSync(args.state, "utf8"));
  let space = null;
  try {
    space = JSON.parse(run("hc", ["get", me, "--json"])).labels?.["herdr.space"] || null;
  } catch {
    // no labels: not shown in a Herdr window, the worker still runs
  }
  const labels = [];
  if (space) labels.push("--label", `herdr.space=${space}`);
  if (space && state.tab) labels.push("--label", `herdr.tab=${state.tab}`);
  const argv = ["run", "--bg", "--json", "--name", args.name, "--cwd", args.cwd, ...(args.on ? ["--on", args.on] : []), ...labels, args.role, task];
  let launched;
  try {
    launched = JSON.parse(run("hc", argv));
  } catch (e) {
    fail(`hc run failed: ${(e.stderr || e.message || "").toString().trim().slice(0, 300)}`);
  }
  if (space && !state.tab) {
    // The first worker of a run opened a new tab: remember it so the rest join it.
    try {
      const tab = findTab(JSON.parse(run("herdr-app", ["ls"])), launched.address);
      if (tab) {
        state.tab = tab;
        try {
          run("herdr-app", ["do", "tab.rename", "--id", tab, "--name", args.run]);
        } catch {
          // cosmetic
        }
      }
    } catch {
      // no window: workers stay unlabeled by tab
    }
  }
  state.workers = { ...(state.workers || {}), [args.name]: { address: launched.address, role: args.role, cwd: args.cwd } };
  fs.mkdirSync(path.dirname(path.resolve(args.state)), { recursive: true });
  fs.writeFileSync(args.state, JSON.stringify(state, null, 2) + "\n");
  console.log(JSON.stringify({ ...launched, tab: state.tab || null, coordinator: me }));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [verb, ...rest] = process.argv.slice(2);
  if (verb === "templates") templates(parseArgs(rest));
  else if (verb === "start") start(parseArgs(rest));
  else fail("usage: hc-worker.mjs templates|start …");
}
